def lookup(name):
    """玩運彩隊名 -> (新聞查詢名, 城市, 緯度, 經度)；認不出來就 None。"""
    name = name or ""
    for keys, q, city, lat, lon in TEAMS:
        if any(k in name for k in keys):
            return q, city, lat, lon
    return None


def place(name):
    hit = lookup(name)
    return (hit[1], hit[2], hit[3]) if hit else None


def news_name(t):
    """新聞查詢用的名字（簡體）：先用對照表，沒有就把玩運彩的隊名去掉常見的繁體字差異。"""
    hit = lookup(t.get("name") or "")
    if hit:
        return hit[0]
    nm = re.sub(r"\s+", "", t.get("name") or "")
    return nm.translate(T2S) or None


